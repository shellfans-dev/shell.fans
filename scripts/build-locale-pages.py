#!/usr/bin/env python3
"""
Generate the English static variant (<page>.en.html) of every page that carries the inline
i18n engine, so nginx can answer an English visitor with English HTML on the very first
byte (deploy/nginx/shell.fans.conf: `map $cookie_shellfans_locale $sf_lang`).

Why a build step and not a runtime swap
---------------------------------------
shell.fans is a static site. Until 2026-09-13 the served HTML was always zh-TW and the
page's own JavaScript replaced every `[data-i18n]` element after DOMContentLoaded when
localStorage said `en` — visitors saw Chinese for a frame (or seconds on slow networks).
The server cannot read localStorage, so the only way to render the right language before
the first paint is to (a) persist the preference in a cookie and (b) already have the
English HTML to serve. This script produces (b) by applying the page's OWN dictionary
(`BASE.en` inside the inline engine) with the SAME semantics as the runtime
`applyTranslations()`:

  data-i18n + data-i18n-attr="x"  → attribute x        (runtime: el.setAttribute)
  data-i18n + data-i18n-html      → inner HTML         (runtime: el.innerHTML)
  data-i18n                       → text, HTML-escaped (runtime: el.textContent)
  missing key                     → zh-TW value, then the key itself (runtime `resolve`)

plus what the runtime meta script does (`<title>`, description, og:title/description) and
the parts the runtime never touches but a first render must get right: `<html lang>`,
og:locale (+alternate), twitter:title/description, the language-switcher check marks and
the crawlable footer baked inside `#sf-footer-root` (translated with the localized strings
of js/sf-footer.js SHELL_BASE, keeping the `data-sf-product` markers the Cloudflare
Worker relies on).

The generated page keeps the engine and both dictionaries, so switching back to zh-TW on
the client still works without a reload, and it keeps every `<a href>` the zh page has.

Usage
-----
  python3 scripts/build-locale-pages.py            # (re)generate all *.en.html
  python3 scripts/build-locale-pages.py --check    # exit 1 if any variant is missing/stale

Run it after ANY change to an engine page or to js/sf-footer.js SHELL_BASE. Node.js is
used only to evaluate the dictionary object literals (they are JavaScript, not JSON).
"""

from __future__ import annotations

import html
import json
import re
import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE_MARK = 'window.__setLocale = function'
# The navigation between these markers is owned by scripts/apply-global-ui-nav.py, which bakes the
# *published* Global UI nav per locale (data-i18n stripped so the page i18n engine never overwrites it).
# This generator must stay agnostic to that block: the zh source carries zh labels, the en variant en
# labels, so we adopt whatever apply-global-ui-nav.py already baked into the target instead of copying
# the zh block across. Pipeline: run build-locale-pages.py first, then apply-global-ui-nav.py on both
# <page>.html and <page>.en.html.
NAV_MARK_OPEN = '<!--sf-gui-nav:start-->'
NAV_MARK_CLOSE = '<!--sf-gui-nav:end-->'
NAV_BLOCK_RE = re.compile(re.escape(NAV_MARK_OPEN) + r'.*?' + re.escape(NAV_MARK_CLOSE), re.S)
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta',
        'param', 'source', 'track', 'wbr'}
BANNER = ('<!-- Generated by scripts/build-locale-pages.py from {src} — DO NOT EDIT. '
          'Served by nginx when cookie shellfans_locale=en. Regenerate instead. -->')

# UI strings that live in js/sf-footer.js build() rather than in SHELL_BASE.
FOOTER_UI = {
    '網站導覽': 'Site navigation',
    '公司資訊': 'Company info',
    '社群連結': 'Social links',
    '切換語言': 'Switch language',
}


